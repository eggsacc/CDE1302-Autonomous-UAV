function print_nav_summary(varargin)
%PRINT_NAV_SUMMARY Compact, paste-friendly numbers for one or more runs.
%   print_nav_summary(resA,resC)   or   print_nav_summary({resA,resC})
% Also locates the largest estimate error over the WHOLE run (metrics only
% score airborne time above 0.2 m) so ground-phase effects are visible.
runs=varargin; if numel(runs)==1 && iscell(runs{1}), runs=runs{1}; end
stages={'TAKEOFF','HOVER','SWEEP','RETURN','SETTLE','DESCEND','ENDPOINT','DONE','FAILED'};
for i=1:numel(runs)
    r=runs{i}; m=r.metrics; c=r.config;
    fprintf('\n=== %s ===\n',m.scenario);
    fprintf('completed %d | %.1f s | max tilt %.2f deg | max speed %.3f m/s\n', ...
        m.mission.completed,m.mission.durationS,m.mission.maxTiltDeg,m.mission.maxSpeedMps);
    fprintf('estimate error (airborne): RMS %.3f m, max %.3f m | heading RMS %.2f deg, max %.2f deg\n', ...
        m.estimation.rmsM,m.estimation.maxM,m.heading.rmsDeg,m.heading.maxAbsDeg);
    e=vecnorm(r.estimatedPosition(:,1:2)-r.position(:,1:2),2,2);
    h=c.frames.homeNed(3)-r.position(:,3);
    [emax,k]=max(e); st=r.diagnostics(k,1);
    fprintf('largest error over whole run: %.3f m at t=%.1f s, height %.3f m, stage %s\n', ...
        emax,r.time(k),h(k),stages{max(1,min(9,st))});
    fprintf('error at end: %.3f m (height %.3f m)\n',e(end),h(end));
    fprintf('tracking, sweep: true vs command RMS %.3f m | true distance to planned route RMS %.3f m, max %.3f m\n', ...
        m.tracking.rmsTrueVsCommandSweepM,m.tracking.rmsTrueDistanceToPlannedRouteSweepM, ...
        m.tracking.maxTrueDistanceToPlannedRouteSweepM);
    fprintf(['landing at touchdown (t=%.1f s): true distance from home %.3f m (drone believed %.3f m); ' ...
        'no-floor slide afterwards %.3f m (artefact)\n'],m.landing.touchdownTimeS, ...
        m.landing.trueHorizontalErrorM,m.landing.estimatedHorizontalErrorM,m.landing.slideAfterTouchdownM);
    t=m.targets.inFlight;
    fprintf('targets in flight: %d/%d confirmed, mean error %.3f m, per tag [%s] m\n', ...
        t.confirmed,t.count,t.meanErrorConfirmedM,num2str(t.errorsM,' %.3f'));
    if isfield(m.targets,'methodB')
        b=m.targets.methodB;
        fprintf('Method B (%s): %d/%d confirmed, mean error %.3f m, per tag [%s] m, corrected track RMS %.3f m\n', ...
            m.methodB.correction,b.confirmed,b.count,b.meanErrorConfirmedM, ...
            num2str(b.errorsM,' %.3f'),m.methodB.correctedTrajectoryRmsM);
    end
    fprintf('landmarks: in view %.1f %% of frames, used %.1f %% | sightings %d used %d rejected %d | yaw-gated frames %.1f %%\n', ...
        100*m.anchors.fractionFramesAnchorVisible,100*m.anchors.fractionFramesAnchorUsed, ...
        m.anchors.sightingsTotal,m.anchors.sightingsUsed,m.anchors.sightingsRejected, ...
        100*m.camera.fractionFramesYawGated);
    if isfield(m,'yaw')
        y=m.yaw;
        fprintf(['yaw (%s): true vs command RMS %.2f deg, max %.2f deg | max true rate %.1f deg/s ' ...
            '(limit %.1f, camera gate %.0f) | turned %.0f deg in total, net %.0f deg | turning %.1f s\n'], ...
            y.mode,y.rmsTrueVsCommandDeg,y.maxAbsTrueVsCommandDeg,y.maxTrueRateDegps,y.limitDegps, ...
            y.cameraGateDegps,y.totalRotationDeg,y.netRotationDeg,y.timeTurningS);
    end
    if isfield(r.execution,'wallClockS')
        fprintf('wall clock %.0f s\n',r.execution.wallClockS);
    end
end
fprintf('\n(Simulation with assumed sensor errors; lecturer RPT controller, not PX4; study EKF, not EKF2.)\n');
end
