"""
The two interfaces mission.py depends on, so a real drone and the simulator
are interchangeable:

    DroneInterface   drone_link.DroneLink   |  sim.SimDrone
    SightingSource   tag_pipeline.TagPipeline |  sim.SimTagSource

These are typing.Protocols: nothing inherits from them, they only document
(and let a type checker verify) what the mission is allowed to call.
"""

from __future__ import annotations

from typing import Callable, Optional, Protocol

from drone_link import Pose


class DroneInterface(Protocol):
    drone_id: int
    dry_run: bool

    def start(self) -> None: ...
    def stop(self) -> None: ...
    def now(self) -> float: ...
    @property
    def connected(self) -> bool: ...
    @property
    def esp_ip(self) -> Optional[str]: ...
    def on_pose(self, fn: Callable[[Pose], None]) -> None: ...
    def latest_pose(self) -> Optional[Pose]: ...
    def pose_at(self, t: float) -> Optional[Pose]: ...
    def yaw_rate_at(self, t: float) -> Optional[float]: ...
    def telemetry_age(self, now: Optional[float] = None) -> float: ...
    def is_stale(self, now: Optional[float] = None) -> bool: ...
    def reset_offset(self) -> None: ...
    def send_start(self) -> bool: ...
    def send_goto(self, x: float, y: float) -> bool: ...
    def send_hold(self) -> bool: ...
    def send_land(self) -> bool: ...


class SightingSource(Protocol):
    def start(self) -> None: ...
    def stop(self) -> None: ...
    @property
    def running(self) -> bool: ...
    def stats(self): ...
    def latest_view(self): ...           # tag_pipeline.CameraView or None
