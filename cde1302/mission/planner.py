#!/usr/bin/env python3
"""
Lawnmower (boustrophedon) waypoint planner.

Turns a search rectangle into a list of (x, y) waypoints in PX4 local NED
(metres, origin = takeoff point), ending back at the start (0, 0).

Run it on its own to check a plan before flying:
    python mission/planner.py               # print waypoints + time estimate
    python mission/planner.py --plot        # also show the path
"""

import argparse
import math
from pathlib import Path

import yaml

CONFIG_PATH = Path(__file__).with_name("config.yaml")


def lane_positions(lo: float, hi: float, max_spacing: float) -> list[float]:
    """Evenly spaced lane positions from lo to hi (inclusive), no gap > max_spacing."""
    if hi <= lo:
        return [lo]
    n_gaps = math.ceil((hi - lo) / max_spacing)
    step = (hi - lo) / n_gaps
    return [lo + i * step for i in range(n_gaps + 1)]


def lawnmower(x_min: float, x_max: float, y_min: float, y_max: float,
              lane_spacing: float, margin: float = 0.0,
              lanes_along: str = "x") -> list[tuple[float, float]]:
    """Sweep waypoints covering the rectangle, shrunk inwards by `margin`.

    lanes_along="x": each lane is a North-South line; lanes step East.
    lanes_along="y": each lane is an East-West line; lanes step North.
    Every second lane is flown in reverse, so the drone zig-zags.
    """
    x0, x1 = x_min + margin, x_max - margin
    y0, y1 = y_min + margin, y_max - margin
    if x1 < x0 or y1 < y0:
        raise ValueError("margin is larger than half the area")

    waypoints = []
    if lanes_along == "x":
        for i, y in enumerate(lane_positions(y0, y1, lane_spacing)):
            ends = [(x0, y), (x1, y)]
            waypoints += ends if i % 2 == 0 else ends[::-1]
    elif lanes_along == "y":
        for i, x in enumerate(lane_positions(x0, x1, lane_spacing)):
            ends = [(x, y0), (x, y1)]
            waypoints += ends if i % 2 == 0 else ends[::-1]
    else:
        raise ValueError(f"lanes_along must be 'x' or 'y', got {lanes_along!r}")
    return [(round(x, 3), round(y, 3)) for x, y in waypoints]


def plan_from_config(cfg: dict) -> list[tuple[float, float]]:
    """Sweep waypoints from config.yaml, plus the return to (0, 0)."""
    a, s = cfg["area"], cfg["sweep"]
    wps = lawnmower(a["x_min"], a["x_max"], a["y_min"], a["y_max"],
                    s["lane_spacing"], a.get("margin", 0.0),
                    s.get("lanes_along", "x"))
    return wps + [(0.0, 0.0)]


def path_length(waypoints, start=(0.0, 0.0)) -> float:
    pts = [start] + list(waypoints)
    return sum(math.dist(p, q) for p, q in zip(pts, pts[1:]))


def load_config(path: Path = CONFIG_PATH) -> dict:
    return yaml.safe_load(Path(path).read_text())


def main() -> None:
    ap = argparse.ArgumentParser(description="Print and plot the lawnmower plan.")
    ap.add_argument("--config", default=str(CONFIG_PATH))
    ap.add_argument("--plot", action="store_true", help="show the path")
    ap.add_argument("--save", help="save the plot to this PNG file")
    ap.add_argument("--export", help="write waypoints as an x,y text file "
                    "for laptop/simple_waypoint_mission.py --waypoints-file")
    args = ap.parse_args()

    cfg = load_config(args.config)
    wps = plan_from_config(cfg)

    if args.export:
        lines = ["# Generated by mission/planner.py from " + Path(args.config).name,
                 "# x,y in metres, NED relative to the takeoff point (x=North, y=East)"]
        lines += [f"{x:.3f},{y:.3f}" for x, y in wps]
        Path(args.export).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"Wrote {len(wps)} waypoints to {args.export}")

    print(f"{len(wps)} waypoints (last one = return to start):")
    for i, (x, y) in enumerate(wps, 1):
        print(f"  {i:2d}: x={x:5.2f}  y={y:5.2f}")

    flight = cfg.get("flight", {})
    length = path_length(wps)
    fly_s = length / flight.get("cruise_speed_mps", 0.10)
    turn_s = len(wps) * flight.get("turn_time_s", 4.0)
    print(f"Path length {length:.1f} m -> about {fly_s:.0f} s flying "
          f"+ {turn_s:.0f} s turning = {(fly_s + turn_s) / 60:.1f} min "
          "(excludes takeoff and landing)")

    if args.plot or args.save:
        import matplotlib.pyplot as plt

        a = cfg["area"]
        fig, ax = plt.subplots(figsize=(6, 6))
        # Map view: East to the right, North up (so plot y on the horizontal axis).
        ax.add_patch(plt.Rectangle((a["y_min"], a["x_min"]),
                                   a["y_max"] - a["y_min"], a["x_max"] - a["x_min"],
                                   fill=False, linestyle="--", label="search area"))
        xs = [0.0] + [w[0] for w in wps]
        ys = [0.0] + [w[1] for w in wps]
        ax.plot(ys, xs, "-o", markersize=4, label="planned path")
        ax.plot(0, 0, "k*", markersize=14, label="takeoff / landing")
        for i, (x, y) in enumerate(wps[:-1], 1):
            ax.annotate(str(i), (y, x), textcoords="offset points", xytext=(5, 5))
        ax.set_xlabel("East, y (m)")
        ax.set_ylabel("North, x (m)")
        ax.set_aspect("equal")
        ax.grid(True, alpha=0.3)
        ax.legend(loc="upper left", bbox_to_anchor=(1.02, 1))
        fig.tight_layout()
        if args.save:
            fig.savefig(args.save, dpi=120)
            print(f"Saved {args.save}")
        if args.plot:
            plt.show()


if __name__ == "__main__":
    main()